#!/bin/bash
# PROTOCOL.md AMENDMENT 1, A10 and A11 -- THE MATCHED NULL FOR FAMILIES (d)
# AND (e), SECOND ATTEMPT. 2026-11-26.
#
# WHY THERE IS A SECOND ATTEMPT. booknull2.sh ran overnight and all 20 runs
# failed with KeyError: R_per_dip, each after 36 minutes of bank building.
# A11 picks family d's winner by R_per_dip averaged over the rotations, and
# chain 1's null books are light() -- no dip column -- so the null could not
# apply the rule it is the null of. Family e died with it because e was built
# after d inside the same try block, and e is the only book near 12%.
#
# WHAT IS DIFFERENT HERE:
#   1. No waiter. Chain 1 finished at 22:22 with 20 of 20 on disk.
#   2. nnfxnullrun2 builds family e FIRST and writes it before touching d.
#   3. The b/c sweep is rebuilt at nnfxbooks' new 'mid' tier on the run's own
#      world and asserted identical to chain 1's R, so d's winner is picked
#      by the same R_per_dip the real run used. Guard 45 covers it.
#   4. FAIL FAST. Last night cost 4.5 hours to learn one thing 20 times. The
#      first failure writes an abort sentinel and every worker that has not
#      started yet exits immediately.
#
# RESUMABLE: a run whose comb_NNN.csv and cell4_NNN.csv are both on disk
# returns at once, so re-running this script picks up where it stopped.
#
# DO NOT EDIT THIS FILE OR code/nnfx{nullrun2,comb,cell4,books,sleeves}.py
# WHILE IT RUNS. Launched with plain nohup, so bash reads it incrementally and
# an edit shifts every later byte offset.
# STOP WITH: bash code/chain/stop_chain.sh $(cat results/chainlogs/booknull2b.pgid)
set -u
cd /Users/jackcuster/fx-data
export FX_COST_TABLE=results/cost_table_h22.csv
LOG=results/chainlogs/booknull2b.log
ABORT=results/chainlogs/booknull2b.abort
ts(){ date "+[%H:%M:%S]"; }
rm -f "$ABORT"

N1=$(ls results/nnfx/books/null/books_*.csv 2>/dev/null | wc -l | tr -d ' ')
if [ "$N1" -lt 20 ]; then
  echo "$(ts) REFUSING TO START -- chain 1 has $N1 of 20 books on disk" >> $LOG
  exit 2
fi
echo "$(ts) START booknull2b -- 20 runs, 3 workers, e before d, fail fast" >> $LOG

# -P 3, NOT 7 AND NOT 4. At 20:28 on 25 Nov seven workers put swap at 7472 of
# 7680 MB with 64 MB of RAM free and the harness killed a background task. The
# machine has since resized swap to 2048 MB total, so there is far LESS room to
# absorb a mistake than there was that night, not more.
seq 0 19 | xargs -P 3 -I{} sh -c '
  if [ -f results/chainlogs/booknull2b.abort ]; then
    echo "$(date +%H:%M:%S) SKIP run {} -- aborted" >> results/chainlogs/booknull2b.log
    exit 0
  fi
  FX_COST_TABLE=results/cost_table_h22.csv \
    python3 code/nnfxnullrun2.py --run {} > results/chainlogs/booknull2b_{}.log 2>&1
  if [ $? -ne 0 ]; then
    touch results/chainlogs/booknull2b.abort
    {
      echo "$(date +%H:%M:%S) FAIL run {} -- ABORTING THE CHAIN"
      echo "---- last 15 lines of booknull2b_{}.log ----"
      tail -15 results/chainlogs/booknull2b_{}.log
      echo "---- end ----"
    } >> results/chainlogs/booknull2b.log
  fi'

ND=$(ls results/nnfx/books/null/comb_*.csv 2>/dev/null | wc -l | tr -d ' ')
NE=$(ls results/nnfx/books/null/cell4_*.csv 2>/dev/null | wc -l | tr -d ' ')
if [ -f "$ABORT" ]; then
  echo "$(ts) ABORTED booknull2b -- $ND of 20 d-runs and $NE of 20 e-runs on disk" >> $LOG
else
  echo "$(ts) OK booknull2b -- $ND of 20 d-runs and $NE of 20 e-runs on disk" >> $LOG
fi
echo "$(ts) DONE booknull2b" >> $LOG
