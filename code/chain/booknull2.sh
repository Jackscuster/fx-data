#!/bin/bash
# PROTOCOL.md AMENDMENT 1, A10 and A11 -- THE MATCHED NULL FOR FAMILIES (d) AND (e).
#
# Families d and e were declared at 20:10 and 20:12, after the 19:41 null chain
# was already running, so they get their own chain over THE SAME 20 SCRAMBLED
# WORLDS: seeds 700000 + run, and nnfxsrc3.zero_edge_frames is deterministic.
# d's construction reads the null run's OWN a/b/c sweep to pick its winner, so
# it must be the same world or it means nothing.
#
# IT WAITS FOR CHAIN 1 RATHER THAN BEING LAUNCHED BY HAND. One armed stage,
# no manual step -- the project's own standard. It needs chain 1's
# books_NNN.csv for each run, and it would also fight chain 1 for cores.
#
# DO NOT EDIT THIS FILE OR code/nnfx{nullrun2,comb,cell4,books,sleeves}.py
# WHILE IT RUNS. Launched with plain nohup, so no frozen snapshot.
# STOP WITH: bash code/chain/stop_chain.sh $(cat results/chainlogs/booknull2.pgid)
set -u
cd /Users/jackcuster/fx-data
export FX_COST_TABLE=results/cost_table_h22.csv
LOG=results/chainlogs/booknull2.log
ts(){ date "+[%H:%M:%S]"; }
echo "$(ts) booknull2 ARMED -- waiting for chain 1's 20 runs" >> $LOG
# ---- the waiter. Chain 1 is resumable, so "20 on disk" is the only signal
# that matters; a count that stops rising with chain 1 gone is a failure and
# the loop says so rather than waiting for ever.
STALL=0; LAST=-1
while :; do
  N=$(ls results/nnfx/books/null/books_*.csv 2>/dev/null | wc -l | tr -d ' ')
  [ "$N" -ge 20 ] && break
  if ! pgrep -f nnfxnullrun.py >/dev/null 2>&1; then
    if [ "$N" = "$LAST" ]; then
      STALL=$((STALL+1))
    else
      STALL=0
    fi
    if [ "$STALL" -ge 3 ]; then
      echo "$(ts) booknull2 REFUSING TO START -- chain 1 is gone with only $N of 20 runs on disk. Re-run the missing ones first: they are resumable." >> $LOG
      exit 2
    fi
  fi
  LAST="$N"
  sleep 120
done
echo "$(ts) chain 1 complete, 20 runs on disk. START booknull2, 7 workers" >> $LOG
seq 0 19 | xargs -P 7 -I{} sh -c \
  'FX_COST_TABLE=results/cost_table_h22.csv python3 code/nnfxnullrun2.py --run {} > results/chainlogs/booknull2_{}.log 2>&1 || echo "$(date +%H:%M:%S) FAIL run {}" >> results/chainlogs/booknull2.log'
ND=$(ls results/nnfx/books/null/comb_*.csv 2>/dev/null | wc -l | tr -d ' ')
NE=$(ls results/nnfx/books/null/cell4_*.csv 2>/dev/null | wc -l | tr -d ' ')
echo "$(ts) OK booknull2 -- $ND of 20 d-runs and $NE of 20 e-runs on disk" >> $LOG
echo "$(ts) DONE booknull2" >> $LOG
